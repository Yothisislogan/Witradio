#!/usr/bin/env python3
"""Stock a test loop for the wit-next staging mount (development plan, Phase 0).

The Phase 0 gate asks for /next to stream a test loop while /stream stays
untouched. Until the new playout engine exists, /next runs on the existing
feeder + ezstream chain, which plays nothing but silence from an empty
library. This writes one short, labelled line-up tone per show into the
wit-next output folder (never the live station's), so /next is audible at
any hour:

    python3 tools/next_test_loop.py            # create
    python3 tools/next_test_loop.py --remove   # clean up

Then start it with:  ./writ --station wit-next start stream
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT / "mac"))
from schedule import load_schedule  # noqa: E402
from station_config import load_station_config  # noqa: E402

TEST_SUFFIX = "_test_loop"


def tone_frequency(index: int) -> float:
    """A different pitch per show, so a listener can hear the show change."""
    return 220.0 * (2 ** (index / 12.0))  # semitone steps up from A3


def write_tone(path: Path, frequency: float, seconds: float) -> None:
    fade_out_start = max(0.0, seconds - 0.5)
    subprocess.run(
        [
            "ffmpeg", "-y", "-v", "error",
            "-f", "lavfi",
            "-i", f"sine=frequency={frequency:.2f}:sample_rate=44100:duration={seconds}",
            "-af", f"volume=-18dB,afade=t=in:d=0.5,afade=t=out:st={fade_out_start}:d=0.5",
            "-ac", "2", "-sample_fmt", "s16",
            str(path),
        ],
        check=True,
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--station", default="wit-next")
    parser.add_argument("--seconds", type=float, default=20.0)
    parser.add_argument("--remove", action="store_true", help="delete the test files")
    args = parser.parse_args()

    station = load_station_config(args.station)
    if station.stream.mount == "/stream":
        parser.error("refusing to stock a test loop on the live /stream mount")
    schedule = load_schedule(station.schedule_path)

    changed = 0
    for index, (show_id, show) in enumerate(sorted(schedule.shows.items())):
        folder = station.bumper_dir / show_id
        audio = folder / f"{show_id}{TEST_SUFFIX}.flac"
        sidecar = audio.with_suffix(".json")
        if args.remove:
            for path in (audio, sidecar):
                if path.exists():
                    path.unlink()
                    changed += 1
            continue
        folder.mkdir(parents=True, exist_ok=True)
        write_tone(audio, tone_frequency(index), args.seconds)
        sidecar.write_text(json.dumps({
            "station_id": station.id,
            "show_id": show_id,
            "display_name": f"Test loop: {show.name}",
            "credit": "Line-up tone generated by WIT-FM",
            "license": "generated",
        }, indent=2))
        changed += 1

    verb = "Removed" if args.remove else "Wrote"
    print(f"{verb} {changed} file(s) under {station.bumper_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
